val ipcRepoPath = run {
    val parent = rootProject.projectDir.parentFile
    if (parent != null) {
        val p = parent.resolve("nervus-ipc")
        if (p.isDirectory) p else null
    } else null
}

if (ipcRepoPath == null) {
    throw GradleException("nervus-ipc not found as sibling directory")
}

val cloneDir = rootProject.projectDir.resolve(".nervus-ipc-clone")

val cloneProtocol by tasks.registering(Copy::class) {
    description = "Copy nervus-ipc protocol sources for compilation"
    // Copy only the generated protocol sources, not the whole repository: a full copy would bring .git, build/
    // and Python output along (hundreds of MB), while compiling only needs jvm/protocol/src/main
    from(ipcRepoPath!!.resolve("jvm/protocol/src/main"))
    into(cloneDir.resolve("jvm/protocol/src/main"))

    // [Don't add onlyIf { !cloneDir.isDirectory }].
    //
    // That would make the copy [never update] after the first build: messages added to nervus-ipc would never
    // show up here, with the symptom "the proto clearly has it, but Kotlin says Unresolved reference",
    // and deleting build/ doesn't help (the copy isn't under build/). It really happened once:
    // the SDK stopped compiling after LaunchComponent was added to ipc, and this was why.
    //
    // The Copy task is incremental by itself: Gradle skips it when the inputs haven't changed, so no hand-written onlyIf is needed.
    doLast {
        logger.lifecycle("nervus-ipc protocol sources synced to $cloneDir")
    }
}

val cleanProtocol by tasks.registering(Delete::class) {
    description = "Clean cloned nervus-ipc repository"
    delete(cloneDir)
}

val protocolSrcDir = cloneDir.resolve("jvm/protocol/src/main")
kotlin.sourceSets.main {
    kotlin.srcDir(protocolSrcDir.resolve("kotlin"))
}
java.sourceSets.main {
    java.srcDir(protocolSrcDir.resolve("java"))
}
// resources/ holds the Provider contract artifacts generated by nervus-ipc (provider/<packageId>/*.binpb).
//
// [They must be wired in explicitly]: cloneProtocol copies everything under jvm/protocol/src/main, so
// the copy has these files, but without srcDir they never get into the SDK jar, and the packaging plugin
// looks for them in jars on runtimeClasspath. The symptom of a missing line is "the artifacts are committed,
// yet nspkg says it can't find them".
//
// Why they travel in the SDK jar instead of the packaging plugin reading ipc from disk: the artifacts are versioned with the pin,
// so "the pin was updated but the binpb is stale", the hardest mismatch to find, can't happen.
java.sourceSets.main {
    resources.srcDir(protocolSrcDir.resolve("resources"))
}

tasks.named("compileKotlin") {
    dependsOn(cloneProtocol)
}

tasks.named("compileJava") {
    dependsOn(cloneProtocol)
}

tasks.named("compileTestKotlin") {
    dependsOn(cloneProtocol)
}

tasks.named("processResources") {
    dependsOn(cloneProtocol)
}

tasks.named("clean") {
    dependsOn(cleanProtocol)
}

// [javac must be told UTF-8 explicitly]. Otherwise it uses the platform default encoding, which on a Chinese-locale Windows
// is GBK, and the Java generated by nervus-ipc used to be full of UTF-8 non-ASCII comments, so every build spat out
// hundreds of "unmappable character for encoding GBK" lines and the comments turned to garbage in the class files.
// Worse, the behaviour [follows the dev machine's locale]: the same code is clean on CI and floods someone's
// machine, and can even fail to compile if a character happens to land on an invalid GBK sequence.
tasks.withType<JavaCompile>().configureEach {
    options.encoding = "UTF-8"
}

